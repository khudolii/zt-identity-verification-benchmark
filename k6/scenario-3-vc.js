/**
 * Scenario 3: Verifiable Credential (VC) with Ed25519 local verification
 *
 * Service B verifies VP/VC signature locally — zero external dependencies.
 * No Keycloak, no IdP of any kind. Fully decentralized.
 *
 * Three phases:
 *   Phase 1 (0-40s):    200 req/s steady — warm baseline
 *   Phase 2 (45-125s):  ramp 200→1000 req/s — stress test (3 × 27s stages)
 *   Phase 3 (130-170s): 200 req/s cooldown — recovery check
 *
 * Expected: comparable latency to JWT (both local crypto),
 * fully stable since no external dependency at all.
 *
 * Usage:
 *   python3 scripts/generate_vp.py  # run once to generate vp.json
 *   k6 run -e SERVICE_B_IP=<ip> k6/scenario-3-vc.js
 */

import http from 'k6/http';
import { check } from 'k6';
import { Trend, Rate, Counter } from 'k6/metrics';

const verificationLatency = new Trend('verification_latency', true);
const errorRate  = new Rate('error_rate');
const reqCounter = new Counter('total_requests');

export const options = {
    scenarios: {
        steady: {
            executor: 'constant-arrival-rate',
            rate: 200,
            timeUnit: '1s',
            duration: '40s',
            preAllocatedVUs: 50,
            maxVUs: 100,
            startTime: '0s',
        },
        ramp: {
            executor: 'ramping-arrival-rate',
            startRate: 200,
            timeUnit: '1s',
            stages: [
                { duration: '27s', target: 400  },
                { duration: '27s', target: 700  },
                { duration: '26s', target: 1000 },
            ],
            preAllocatedVUs: 200,
            maxVUs: 500,
            startTime: '45s',
        },
        cooldown: {
            executor: 'constant-arrival-rate',
            rate: 200,
            timeUnit: '1s',
            duration: '40s',
            preAllocatedVUs: 50,
            maxVUs: 100,
            startTime: '130s',
        },
    },
    thresholds: {
        'verification_latency': ['p(95)<2000'],
        'error_rate':           ['rate<0.10'],
    },
};

const SERVICE_B_IP = __ENV.SERVICE_B_IP || 'localhost';
const URL          = `http://${SERVICE_B_IP}/api/resource/vc`;

// VP pre-generated by scripts/generate_vp.py
// Run k6 from project root: k6 run k6/scenario-3-vc.js
const VP_JSON = open('../vp.json');

export default function () {
    const res = http.post(URL, VP_JSON, {
        headers: { 'Content-Type': 'application/json' },
        timeout: '5s',
    });

    const ok = check(res, {
        'status is 200': (r) => r.status === 200,
        'response allowed': (r) => {
            try { return JSON.parse(r.body).status === 'allowed'; }
            catch { return false; }
        },
    });

    verificationLatency.add(res.timings.duration);
    errorRate.add(!ok);
    reqCounter.add(1);
}