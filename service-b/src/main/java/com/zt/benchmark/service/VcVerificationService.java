package com.zt.benchmark.service;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.SerializationFeature;
import jakarta.annotation.PostConstruct;
import org.bouncycastle.crypto.params.Ed25519PublicKeyParameters;
import org.bouncycastle.crypto.signers.Ed25519Signer;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Service;

import java.util.Base64;
import java.util.Map;

/**
 * Scenario 3: Verifiable Credential (VC) with Ed25519 local verification.
 *
 * Models the DID/VC-based decentralized trust approach.
 * A VC is a signed JSON document containing claims about the subject.
 * The public key is pre-loaded from config (generated by scripts/generate_vp.py).
 *
 * In a full DID/VC implementation (did:key method), the public key would be
 * derived directly from the DID string — no external registry needed.
 * This implementation isolates the cryptographic verification overhead,
 * which is the relevant metric for this benchmark.
 *
 * No Keycloak, no network calls — fully decentralized verification.
 * If Keycloak goes down: verification continues working (failover test).
 *
 * Latency = local Ed25519 signature verification only.
 *
 * Expected VP structure (generated by scripts/generate_vp.py):
 * {
 *   "vc": {
 *     "issuer": "did:key:z6Mk...",
 *     "subject": "did:key:z6Mk...",
 *     "issuanceDate": "2026-...",
 *     "claims": { "role": "backend-service", "department": "payments" }
 *   },
 *   "signature": "<base64url Ed25519 signature over vc JSON>"
 * }
 */
@Service
public class VcVerificationService {

    @Value("${vc.trusted-public-key}")
    private String trustedPublicKeyBase64;

    // ORDER_MAP_ENTRIES_BY_KEYS produces the same key order as Python's sort_keys=True
    private final ObjectMapper objectMapper = new ObjectMapper()
            .configure(SerializationFeature.ORDER_MAP_ENTRIES_BY_KEYS, true);
    private Ed25519PublicKeyParameters publicKey;

    @PostConstruct
    public void init() {
        if (trustedPublicKeyBase64 == null || trustedPublicKeyBase64.isBlank()) {
            throw new IllegalStateException(
                "TRUSTED_ISSUER_PUBLIC_KEY environment variable is not set. " +
                "Run scripts/generate_vp.py first to generate the keypair."
            );
        }
        byte[] keyBytes = Base64.getDecoder().decode(trustedPublicKeyBase64);
        this.publicKey = new Ed25519PublicKeyParameters(keyBytes, 0);
    }

    /**
     * Verifies VP structure, Ed25519 signature, and policy claims.
     * Fully local — no network calls of any kind.
     */
    public boolean verify(String vpJson) {
        try {
            Map<?, ?> vp = objectMapper.readValue(vpJson, Map.class);

            Object vcObj = vp.get("vc");
            String signature = (String) vp.get("signature");

            if (vcObj == null || signature == null) {
                return false;
            }

            // Serialize VC to canonical bytes — same bytes that were signed
            byte[] vcBytes = objectMapper.writeValueAsBytes(vcObj);
            byte[] sigBytes = decodeBase64Url(signature);

            // Verify Ed25519 signature locally using pre-loaded public key
            Ed25519Signer signer = new Ed25519Signer();
            signer.init(false, publicKey);
            signer.update(vcBytes, 0, vcBytes.length);

            if (!signer.verifySignature(sigBytes)) {
                return false;
            }

            // Policy evaluation: check required claims
            // Same policy expression works across any domain — no IAM mapping needed
            @SuppressWarnings("unchecked")
            Map<String, Object> claims = (Map<String, Object>)
                    ((Map<?, ?>) vcObj).get("claims");

            return claims != null
                    && "backend-service".equals(claims.get("role"));

        } catch (Exception e) {
            return false;
        }
    }

    // Python strips '=' padding (rstrip('=')); Java's URL decoder requires it back
    private static byte[] decodeBase64Url(String s) {
        int pad = (4 - s.length() % 4) % 4;
        return Base64.getUrlDecoder().decode(s + "=".repeat(pad));
    }
}
